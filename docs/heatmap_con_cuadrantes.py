import cv2
import torch
import numpy as np
from transformers import AutoFeatureExtractor, AutoModel
from PIL import Image
import os

def check_video_exists(video_path):
    """Verificar que el video existe"""
    if not os.path.exists(video_path):
        raise FileNotFoundError(f"El archivo de video no existe: {video_path}")
    return True

def get_attention_map(model, feature_extractor, image):
    """Extraer mapa de atención del modelo DINO"""
    # Preprocesar imagen
    inputs = feature_extractor(images=image, return_tensors="pt")

    with torch.no_grad():
        outputs = model(**inputs)

        # Para DINO, usar el token [CLS] o promediar todos los tokens
        # Obtener las características del último layer
        last_hidden_states = outputs.last_hidden_state  # [batch, seq_len, hidden_dim]

        # DINO usa patches, necesitamos reshapear para obtener el mapa espacial
        # El primer token es [CLS], el resto son patches
        patch_tokens = last_hidden_states[0, 1:]  # Excluir [CLS] token

        # Calcular la atención promediando las dimensiones de características
        attention_map = torch.mean(patch_tokens, dim=-1)  # Promediar características

        # Determinar el tamaño de la grilla de patches
        num_patches = attention_map.shape[0]
        grid_size = int(np.sqrt(num_patches))

        # Verificar que es una grilla cuadrada válida
        if grid_size * grid_size != num_patches:
            # Si no es cuadrada, usar interpolación
            grid_size = int(np.sqrt(num_patches))
            attention_map = attention_map[:grid_size*grid_size]

        # Reshapear a mapa 2D
        attention_map = attention_map.reshape(grid_size, grid_size)

    return attention_map.numpy()

def create_saliency_heatmap(attention_map, target_size):
    """Crear heatmap a partir del mapa de atención"""
    # Normalizar el mapa de atención
    attention_map = (attention_map - attention_map.min()) / (attention_map.max() - attention_map.min())

    # Redimensionar al tamaño objetivo
    attention_resized = cv2.resize(attention_map, target_size, interpolation=cv2.INTER_CUBIC)

    # Crear heatmap con colormap
    heatmap = cv2.applyColorMap(np.uint8(255 * attention_resized), cv2.COLORMAP_JET)

    return heatmap, attention_resized

