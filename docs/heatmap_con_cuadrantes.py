def create_heatmap_with_quadrants(frame, heatmap, quadrants):
    """Combinar heatmap con cuadrantes y porcentajes en un solo panel"""
    # Superponer heatmap con frame original
    superimposed = cv2.addWeighted(frame, 0.4, heatmap, 0.6, 0)

    h, w = superimposed.shape[:2]

    # Colores para las líneas y texto
    line_color = (255, 255, 255)  # Blanco
    text_color = (0, 255, 0)      # Verde
    bg_color = (0, 0, 0)          # Negro para fondo del texto

    # Dibujar líneas de división (3x3 grid)
    quadrant_h = h // 3
    quadrant_w = w // 3

    # Líneas horizontales
    for i in range(1, 3):
        y = i * quadrant_h
        cv2.line(superimposed, (0, y), (w, y), line_color, 2)

    # Líneas verticales
    for j in range(1, 3):
        x = j * quadrant_w
        cv2.line(superimposed, (x, 0), (x, h), line_color, 2)

    # Dibujar porcentajes en cada cuadrante
    font = cv2.FONT_HERSHEY_SIMPLEX
    font_scale = 0.8
    thickness = 2

    for quadrant_id, data in quadrants.items():
        percentage = data['percentage']
        bounds = data['bounds']

        # Calcular posición del texto (abajo y centro del cuadrante)
        center_x = (bounds[0] + bounds[2]) // 2
        bottom_y = bounds[3] - 10  # 10 píxeles desde el borde inferior

        # Texto a mostrar
        text = f"Q{quadrant_id}: {percentage:.1f}%"

        # Calcular tamaño del texto para el fondo
        (text_w, text_h), baseline = cv2.getTextSize(text, font, font_scale, thickness)

        # Dibujar fondo negro para el texto
        bg_x1 = center_x - text_w // 2 - 5
        bg_y1 = bottom_y - text_h - 5
        bg_x2 = center_x + text_w // 2 + 5
        bg_y2 = bottom_y + 5

        cv2.rectangle(superimposed, (bg_x1, bg_y1), (bg_x2, bg_y2), bg_color, -1)

        # Dibujar el texto
        text_x = center_x - text_w // 2
        text_y = bottom_y
        cv2.putText(superimposed, text, (text_x, text_y), font, font_scale, text_color, thickness)

    return superimposed

