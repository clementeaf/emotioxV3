def calculate_quadrant_attention(attention_map):
    """Calcular el porcentaje de atención en cada cuadrante (3x3 grid)"""
    h, w = attention_map.shape

    # Dividir en 3x3 cuadrantes
    quadrant_h = h // 3
    quadrant_w = w // 3

