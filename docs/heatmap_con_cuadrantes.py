# Definir modelo DeepGaze II
class DeepGazeII(nn.Module):
    def __init__(self):
        super(DeepGazeII, self).__init__()
        self.backbone = timm.create_model('vgg19_bn', pretrained=True, features_only=True)
        self.readout = nn.Conv2d(512, 1, kernel_size=1)

    def forward(self, x):
        features = self.backbone(x)[-1]
        saliency = self.readout(features)
        saliency = F.relu(saliency)
        saliency = F.interpolate(saliency, size=x.shape[2:], mode='bilinear', align_corners=False)
        return saliency

